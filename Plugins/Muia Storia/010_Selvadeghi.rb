  def self.pesca_pesada(lista)
    pesi = lista.map { |sp| d = GameData::Species.try_get(sp); d ? [d.catch_rate, 3].max : 0 }
    tot = pesi.sum
    return nil if tot <= 0
    r = rand(tot)
    lista.each_with_index do |sp, i|
      r -= pesi[i]
      return sp if r < 0
    end
    return lista.last
  end

  def self.selvadego_acqua?(specie)
    d = GameData::Species.try_get(specie)
    return d && d.types.include?(:WATER)
  end

  def self.cambia_selvadego(encounter)
    return if !encounter || !encounter[0]
    livel = encounter[1] || 5
    if rand(PROB_LEGGENDARIO) == 0
      sp = LEGGENDARI_SELVADEGHI.select { |s| GameData::Species.exists?(s) }.sample
      if sp
        encounter[0] = sp
        encounter[1] = [livel + 5, GameData::GrowthRate.max_level].min
        return
      end
    end
    return if rand(100) >= PROB_RANDOM
    lista = selvadego_acqua?(encounter[0]) ? SELVADEGHI_ACQUA : SELVADEGHI_TERA
    sp = pesca_pesada(lista.select { |s| GameData::Species.exists?(s) })
    return if !sp
    encounter[0] = specie_per_livel(sp, livel)
  end
